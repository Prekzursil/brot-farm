#!/usr/bin/env python3
"""Regenerate the APRS community collection index from collection/*.aprs.json.

Writes:
    collection/index.json          — {schema: {version: 1}, entries: [...]}
    docs/assets/collection.js     — window.BROT_COLLECTION = <index>;
      (script include, like catalogue.js: no fetch, works on file://)

Every *.aprs.json under the collection dir must pass scripts/validate_aprs.py
(the intake workflow runs this before opening its curation PR, so a broken
record can never land in the rendered page).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent.parent
COLLECTION = HERE / "collection"
DOCS = HERE / "docs"

JS_HEADER = (
    "// generated by scripts/build_collection.py — do not edit by hand\n"
    "// (every entry validated by scripts/validate_aprs.py at build time)\n"
)


def build_index(collection_dir: Path) -> list[dict[str, Any]]:
    """Validate + load every record; entries sorted by (created, file)."""
    from scripts.validate_aprs import validate_file

    if not collection_dir.is_dir():
        raise SystemExit(f"collection dir {collection_dir} does not exist")
    entries: list[dict[str, Any]] = []
    problems: list[str] = []
    for p in sorted(collection_dir.glob("*.aprs.json")):
        reasons = validate_file(p)
        if reasons:
            problems.append(f"{p.name}: " + "; ".join(reasons))
            continue
        rec = json.loads(p.read_text(encoding="utf-8"))
        entries.append({**rec, "file": p.name})
    if problems:
        raise SystemExit("invalid APRS in collection:\n  " + "\n  ".join(problems))
    entries.sort(key=lambda e: (e["created"], e["file"]))
    return entries


def write_outputs(collection_dir: Path, docs_dir: Path) -> list[dict[str, Any]]:
    entries = build_index(collection_dir)
    index: dict[str, Any] = {"schema": {"version": 1}, "entries": entries}
    (collection_dir / "index.json").write_text(
        json.dumps(index, indent=2) + "\n", encoding="utf-8"
    )
    assets = docs_dir / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "collection.js").write_text(
        JS_HEADER + f"window.BROT_COLLECTION = {json.dumps(index)};\n",
        encoding="utf-8",
    )
    print(
        f"collection: {len(entries)} entries -> "
        f"{collection_dir / 'index.json'} + {assets / 'collection.js'}"
    )
    return entries


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(
        prog="build_collection", description="Regenerate the APRS collection index."
    )
    ap.add_argument("--collection-dir", type=Path, default=None)
    ap.add_argument("--docs-dir", type=Path, default=None)
    args = ap.parse_args(argv)
    write_outputs(args.collection_dir or COLLECTION, args.docs_dir or DOCS)


if __name__ == "__main__":  # pragma: no cover
    import sys

    # allow `python scripts/build_collection.py` from the repo root: direct
    # script execution puts scripts/ (not the root) on sys.path[0]
    sys.path.insert(0, str(HERE))
    main()
